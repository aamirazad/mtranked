// Writes migrations/0002-0005_ghost_bots_*.sql: 12 "ghost" bot accounts with three recorded races
// each, so ghost races work before real players exist. Deterministic, so re-running it
// produces the same file (commit the output).
//   pnpm --filter @mtr/worker exec tsx scripts/gen-ghosts.ts
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { BACKSPACE, RANKED_SETTINGS, finalStats, generateText, replay, seededRandom, type Keystroke } from "@mtr/engine";
import { packKeys } from "../src/keys";

const NOW = "cast(unixepoch('subsec') * 1000 as integer)";
const uuid = (s: string) => {
  const h = createHash("sha256").update(s).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const str = (s: string) => `'${s.replace(/'/g, "''")}'`;

function synthesize(text: string, wpm: number, seed: string): Keystroke[] {
  const rand = seededRandom(seed);
  const mean = 12000 / wpm; // ms per char
  const keys: Keystroke[] = [];
  let t = 250 + rand() * 300;
  const gauss = () => Math.sqrt(-2 * Math.log(rand() || 1e-9)) * Math.cos(2 * Math.PI * rand());
  for (const ch of text) {
    const dt = () => Math.max(25, mean * Math.exp(0.35 * gauss() - 0.06));
    if (rand() < 0.025 && ch !== " ") {
      t += dt();
      keys.push({ k: "x", t: Math.round(t) });
      t += dt() * 1.6;
      keys.push({ k: BACKSPACE, t: Math.round(t) });
    }
    t += dt();
    keys.push({ k: ch, t: Math.round(t) });
  }
  return keys;
}

const BOTS = [
  ["ghost_pebble", 38], ["ghost_quill", 47], ["ghost_ink", 55], ["ghost_fern", 62],
  ["ghost_ember", 70], ["ghost_harbor", 78], ["ghost_lumen", 86], ["ghost_vale", 94],
  ["ghost_comet", 103], ["ghost_onyx", 112], ["ghost_zephyr", 124], ["ghost_nova", 138],
] as const;

const HEADER = [
  "-- Generated by scripts/gen-ghosts.ts: ghost bots with recorded races for ghost races.",
  "-- Bots can't sign in (no password) and never show on the leaderboard.",
];
// D1 takes each migration file as one query, capped at 100 KB: three bots per file
const PER_FILE = 3;
let out: string[] = [];
for (const [b, [name, wpm]] of BOTS.entries()) {
  if (b % PER_FILE === 0) out = [...HEADER];
  const id = uuid(`bot:${name}`);
  const rating = 1500 + (wpm - 80) * 9;
  out.push(
    `insert into users (id, email, password_hash, display_name, is_bot, email_verified_at, created_at)
  values (${str(id)}, ${str(name + "@bots.invalid")}, '!', ${str(name)}, 1, ${NOW}, ${NOW});`,
    `insert into ratings (user_id, season_id, rating, rd, races, peak, updated_at)
  values (${str(id)}, 0, ${rating}, 80, 20, ${rating}, ${NOW});`,
  );
  for (let i = 0; i < 3; i++) {
    const seed = `${name}-${i}`;
    const { text } = await generateText(RANKED_SETTINGS, seed);
    const keys = synthesize(text, wpm, seed + "k");
    const dur = keys.at(-1)!.t;
    const stats = finalStats(replay(text, keys), dur);
    const matchId = uuid(`match:${seed}`);
    out.push(
      `insert into matches (id, mode, seed, text_settings, text, season_id, started_at, finished_at, players)
  values (${str(matchId)}, 'seed', ${str(seed)}, ${str(JSON.stringify(RANKED_SETTINGS))}, ${str(text)}, 0, ${NOW}, ${NOW}, 1);`,
      `insert into match_players (match_id, slot, user_id, placement, wpm, raw, accuracy, finished_at_ms, finished, rating_before, duration_ms)
  values (${str(matchId)}, 0, ${str(id)}, 1, ${stats.wpm}, ${stats.raw}, ${stats.acc}, ${dur}, 1, ${rating}, ${dur});`,
      `insert into replays (match_id, slot, keystrokes) values (${str(matchId)}, 0, ${str(packKeys(keys))});`,
    );
  }
  if (b % PER_FILE === PER_FILE - 1 || b === BOTS.length - 1) {
    const n = 2 + Math.floor(b / PER_FILE);
    const file = `${String(n).padStart(4, "0")}_ghost_bots_${Math.floor(b / PER_FILE) + 1}.sql`;
    writeFileSync(join(import.meta.dirname, "..", "migrations", file), out.join("\n") + "\n");
  }
}
console.log(`wrote ${BOTS.length} bots`);
